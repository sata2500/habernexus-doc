/** Eski kayıtlardaki adlar (lucide'de yeniden adlandırılanlar) */
const ALIASES: Record<string, LucideIcon> = {
  Gamepad: Gamepad2,
  EuroIcon: Euro,
  LineChart: ChartLine,
  PieChart: ChartPie,
  BarChart: ChartColumn,
  Home: House,
};

const LOOKUP = new Map(
  Object.entries({ ...CATEGORY_ICONS, ...ALIASES }).map(([name, icon]) => [name.toLowerCase(), icon]),
);

export const CATEGORY_ICON_NAMES = Object.keys(CATEGORY_ICONS);

export function categoryIcon(name: string | null | undefined): LucideIcon | null {
  return name ? LOOKUP.get(name.trim().toLowerCase()) ?? null : null;
}
